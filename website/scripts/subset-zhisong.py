#!/usr/bin/env python3
"""Slice the official LXGW Neo ZhiSong release into unicode-range woff2 files.

Usage: python3 website/scripts/subset-zhisong.py LXGWNeoZhiSong.ttf
Needs fonttools and brotli. The font is IPA Font License 1.0: the site must keep
public/fonts/LICENSES.txt and the footer switch back to the original IPA font.
zhisong-ranges.txt holds one unicode-range per slice (taken from @fontsource/noto-serif-sc 5.3.1),
so a page fetches only the blocks it uses.
"""
import hashlib
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

RELEASE = 'https://github.com/lxgw/LxgwNeoZhiSong/releases/download/v1.070/LXGWNeoZhiSong.ttf'
SHA256 = 'c42000b59caffe8ccfcd1c90aa2841dcafa866cf24769cc1b10c3708c671f207'
WEBSITE = Path(__file__).resolve().parent.parent
RANGES = Path(__file__).with_name('zhisong-ranges.txt')
OUT = WEBSITE / 'src/fonts/lxgw-neo-zhisong'

def codepoints(spec):
    for part in spec.split(','):
        lo, _, hi = part.strip().removeprefix('U+').partition('-')
        yield from range(int(lo, 16), int(hi or lo, 16) + 1)

def main(source):
    if hashlib.sha256(Path(source).read_bytes()).hexdigest() != SHA256:
        sys.exit(f'Expected the v1.070 release ({RELEASE})')
    cmap = set(TTFont(source)['cmap'].getBestCmap())
    ranges = RANGES.read_text().split()
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob('*.woff2'):
        old.unlink()
    faces = []
    for index, spec in enumerate(ranges):
        wanted = sorted(cmap.intersection(codepoints(spec)))
        if not wanted:
            continue
        options = subset.Options(flavor='woff2', hinting=False, layout_features=['*'], name_IDs=['*'])
        font = TTFont(source)
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=wanted)
        subsetter.subset(font)
        font.flavor = 'woff2'
        font.save(OUT / f'{index:03}.woff2')
        faces.append(f'@font-face{{font-family:"LXGW Neo ZhiSong";font-style:normal;font-weight:400;font-display:swap;'
                     f'src:url(./{index:03}.woff2) format("woff2");unicode-range:{spec.strip()}}}')
    (OUT / 'index.css').write_text('/* Generated by website/scripts/subset-zhisong.py from LXGW Neo ZhiSong v1.070 (IPA Font License 1.0, see /fonts/LICENSES.txt). */\n' + '\n'.join(faces) + '\n')
    print(f'{len(faces)} slices, {sum(f.stat().st_size for f in OUT.glob("*.woff2")) // 1024} KB')

if __name__ == '__main__':
    main(sys.argv[1])
